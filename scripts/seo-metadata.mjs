export function normalizePath(route) {
  if (!route || route === '/') return '/';
  return `/${route.replace(/^\/+|\/+$/g, '')}`;
}

export function makeNewsSeo(route) {
  const slug = normalizePath(route).split('/').pop() || 'novost';
  const readable = slug.replace(/[-_]+/g, ' ');
  return {
    title: `Новость: ${readable} | Центр Притяжения`,
    description: `Новость Центра Притяжения о судоподъёме, водолазных работах и морской отрасли: ${readable}. Подробности и актуальная информация.`,
  };
}

export function getRouteSeo(route) {
  const normalized = normalizePath(route);
  return ROUTE_SEO[normalized] || (normalized.startsWith('/news/') ? makeNewsSeo(normalized) : DEFAULT_SEO);
}
